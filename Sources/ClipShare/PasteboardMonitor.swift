import AppKit
import UniformTypeIdentifiers

/// What the monitor captured from the system clipboard.
enum CapturedContent {
    case text(String)
    case png(Data)
}

/// Polls NSPasteboard's change count and reports new text or images.
@MainActor
final class PasteboardMonitor {
    /// PNGs larger than this are not recorded (matches omaclip's default limit).
    static let maxImageBytes = 5 * 1024 * 1024

    var onCapture: ((CapturedContent) -> Void)?

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?

    /// Types that password managers set to ask clipboard tools not to record the item.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init() {
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    /// Call right after writing to the pasteboard so our own write is not recorded as a new copy.
    func ignoreCurrentContents() {
        lastChangeCount = pasteboard.changeCount
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        if let content = read() { onCapture?(content) }
    }

    private func read() -> CapturedContent? {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return nil }

        // A copied image file in Finder: share the image itself rather than its name.
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [
            .urlReadingFileURLsOnly: true,
            .urlReadingContentsConformToTypes: [UTType.image.identifier],
        ]) as? [URL], let url = urls.first, let data = try? Data(contentsOf: url), let png = Self.pngData(from: data) {
            return png.count <= Self.maxImageBytes ? .png(png) : nil
        }
        if let text = pasteboard.string(forType: .string), !text.isEmpty {
            return .text(text)
        }
        if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff), let png = Self.pngData(from: data) {
            return png.count <= Self.maxImageBytes ? .png(png) : nil
        }
        return nil
    }

    static func pngData(from data: Data) -> Data? {
        if data.starts(with: [0x89, 0x50, 0x4E, 0x47]) { return data }
        if let rep = NSBitmapImageRep(data: data), let png = rep.representation(using: .png, properties: [:]) { return png }
        guard let image = NSImage(data: data), let tiff = image.tiffRepresentation,
              let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }
}
